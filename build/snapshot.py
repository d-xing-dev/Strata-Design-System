#!/usr/bin/env python3
"""Emit dist/skill-snapshot/ -- the flattened copy of Strata that ships inside the
`raise-design-fidelity` UX skill.

WHY THIS EXISTS
---------------
The repo's central guarantee is that documentation cannot drift from the CSS, because
`make.py` generates both from the same source. That guarantee stops at a copy boundary.
The skill's `references/design-system/` directory was assembled by hand, and over two
weeks it accumulated three defects nobody could see:

  1. `usage.md` taught twelve type tokens while the CSS beside it defined eight. Unknown
     `st-*` classes are silent no-ops in CSS, so following it produced unstyled output
     and no error anywhere.
  2. `LICENCE-AND-ATTRIBUTION.md` carried a superseded licence position.
  3. `strata-scaffold.css` was not a build output at all -- it was the hand-authored
     encode *target specification*, whose own header said to regenerate and delete it
     once `build/` was updated. It differed from the real build in `--st-border-subtle-00`,
     the hairline: opaque hex where the build emits alpha. An alpha border composites
     over stacked layers differently from a fixed hex, which is precisely the class of
     difference the real-alpha contrast audit exists to catch.

All three have the same cause and the same fix: **the snapshot must be a build output**,
so that copying is something the build does rather than something a person remembers.

TWO ENTRY POINTS
----------------
  emit()   assemble dist/skill-snapshot/ from dist/ and the repo root.
  check()  verify an existing snapshot still matches its sources. Returns drifted files.

  python3 build/snapshot.py            emit
  python3 build/snapshot.py --check    verify, exit 1 on drift

`make.py` calls emit_if_complete() at the end of every run: it emits once every declared
brand has a current build, and otherwise says which brand is missing rather than shipping
a half snapshot.

EVERY FILE IN THE SNAPSHOT HAS A SOURCE IN THIS REPO. That is the invariant. The one
authored file, the snapshot's own README, lives at build/snapshot/README.md -- before this
module existed its only copy was inside the delivered .skill archive, which is why nobody
noticed it going stale.
"""

from __future__ import annotations
import os, sys, json, shutil, hashlib

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DIST = os.path.join(ROOT, "dist")
OUT = os.path.join(DIST, "skill-snapshot")
AUTHORED = os.path.join(ROOT, "build", "snapshot")

# Root docs copied verbatim, lowercased to the flattened skill's naming.
DOCS = {
    "USAGE.md": "usage.md",
    "COMPOSITION.md": "composition.md",
    "PATTERNS.md": "patterns.md",
    "RESOLUTION-MAP.md": "resolution-map.md",
    "SHELL-SPEC.md": "shell-spec.md",
    "LICENCE-AND-ATTRIBUTION.md": "LICENCE-AND-ATTRIBUTION.md",
    "NOTICE": "NOTICE",
}

STATE_BEGIN = "<!-- SNAPSHOT-STATE:BEGIN -- generated by build/snapshot.py, do not edit -->"
STATE_END = "<!-- SNAPSHOT-STATE:END -->"


def _brands() -> list[str]:
    sys.path.insert(0, os.path.join(ROOT, "build"))
    import color
    return sorted(color.BRANDS.keys())


def _sha(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _plan() -> tuple[list[tuple[str, str]], list[str]]:
    """Return [(source_abs, dest_name)] plus a list of problems that must block emit."""
    pairs, problems = [], []
    brands = _brands()

    newest_src = max(
        os.path.getmtime(os.path.join(ROOT, "build", f))
        for f in os.listdir(os.path.join(ROOT, "build"))
        if f.endswith(".py")
    )

    for b in brands:
        css = os.path.join(DIST, b, "strata.css")
        if not os.path.exists(css):
            problems.append(f"{b}: no build yet -- run STRATA_BRAND={b} python3 build/make.py")
            continue
        # A brand built before the current source is a brand whose CSS is not what
        # build/ would now emit. Shipping it silently is how the deloitte file went stale.
        if os.path.getmtime(css) < newest_src:
            problems.append(
                f"{b}: dist is older than build/ -- rebuild with STRATA_BRAND={b} python3 build/make.py")
            continue
        pairs.append((css, f"strata-{b}.css"))
        ref = os.path.join(DIST, b, f"reference-{b}.html")
        if os.path.exists(ref):
            pairs.append((ref, f"reference-{b}.html"))

    icons = os.path.join(DIST, brands[0], "strata-icons.svg")
    for b in brands:
        cand = os.path.join(DIST, b, "strata-icons.svg")
        if os.path.exists(cand):
            icons = cand
            break
    if os.path.exists(icons):
        pairs.append((icons, "strata-icons.svg"))
    else:
        problems.append("strata-icons.svg missing from every brand's dist")

    for src, dest in DOCS.items():
        p = os.path.join(ROOT, src)
        if os.path.exists(p):
            pairs.append((p, dest))
        else:
            problems.append(f"{src} missing from the repo root")

    # The construction floor's checker travels with the system, not as a hand-copied
    # twin in each skill. It said an identical copy lived in the repo while none did.
    pc = os.path.join(ROOT, "build", "production_check.py")
    if os.path.exists(pc):
        pairs.append((pc, "production-check.py"))
    else:
        problems.append("build/production_check.py missing -- the skills instruct running it")

    readme = os.path.join(AUTHORED, "README.md")
    if not os.path.exists(readme):
        problems.append(
            "build/snapshot/README.md missing -- the snapshot's own README is authored and "
            "must live in the repo, not only inside the delivered .skill")

    return pairs, problems


def _state_block(pairs: list[tuple[str, str]], brands: list[str]) -> str:
    """Content-addressed, so it diffs only when something actually changed -- a build
    timestamp would churn on every run and teach the reader to ignore this block."""
    lines = [
        STATE_BEGIN,
        "> **Snapshot state — generated by `build/snapshot.py`.** Every file below is copied from",
        f"> this repo by the build; none is maintained by hand. Brands: {', '.join(brands)}.",
        ">",
        "> | File | Source | sha256 |",
        "> |---|---|---|",
    ]
    for src, dest in sorted(pairs, key=lambda p: p[1]):
        rel = os.path.relpath(src, ROOT).replace(os.sep, "/")
        lines.append(f"> | `{dest}` | `{rel}` | `{_sha(src)[:12]}` |")
    lines += [
        ">",
        "> Verify with `python3 build/snapshot.py --check`, which fails on any drift between",
        "> this directory and its sources. A hand-edit here is lost on the next build and, worse,",
        "> breaks the only reason to trust the snapshot at all.",
        STATE_END,
    ]
    return "\n".join(lines)


def _render_readme(pairs, brands) -> str:
    src = open(os.path.join(AUTHORED, "README.md"), encoding="utf-8").read()
    block = _state_block(pairs, brands)
    if STATE_BEGIN in src and STATE_END in src:
        head = src[: src.index(STATE_BEGIN)]
        tail = src[src.index(STATE_END) + len(STATE_END):]
        return head + block + tail
    return block + "\n\n" + src


def emit(strict: bool = True) -> list[str]:
    pairs, problems = _plan()
    if problems and strict:
        raise SystemExit("SNAPSHOT REFUSED\n  " + "\n  ".join(problems))
    if problems:
        return problems

    brands = _brands()
    os.makedirs(OUT, exist_ok=True)
    written = {}
    for src, dest in pairs:
        shutil.copy2(src, os.path.join(OUT, dest))
        written[dest] = {"source": os.path.relpath(src, ROOT).replace(os.sep, "/"),
                         "sha256": _sha(src)}

    readme = _render_readme(pairs, brands)
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme)
    written["README.md"] = {"source": "build/snapshot/README.md (authored, state block generated)",
                            "sha256": hashlib.sha256(readme.encode()).hexdigest()}

    # Anything here that the plan did not write is a leftover from an older layout and
    # would be shipped as though it were current -- exactly the deloitte failure.
    for stale in set(os.listdir(OUT)) - set(written) - {"manifest.json"}:
        os.remove(os.path.join(OUT, stale))
        print(f"snapshot     removed stale file {stale}")

    # The packaging reference pages point at strata-<brand>.css, which exists HERE and
    # nowhere else -- so this is the only place their <link> can be proven to resolve.
    # Both pages once shipped rendering unstyled; the reader concluded the system looks
    # like that. Prove it, do not assume the href is right.
    import production_check
    refs = [os.path.join(OUT, f"reference-{b}.html") for b in brands
            if os.path.exists(os.path.join(OUT, f"reference-{b}.html"))]
    if refs:
        mode, findings = production_check.check(refs)
        if findings:
            raise SystemExit("SNAPSHOT REFUSED — packaging reference page fails its own gate\n  "
                             + "\n  ".join(findings))
        print(f"snapshot     [{mode}] packaging reference pages clean ({len(refs)})")

    with open(os.path.join(OUT, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump({"brands": brands, "files": written}, f, indent=2, sort_keys=True)

    print(f"snapshot     {len(written)} files -> dist/skill-snapshot/ ({', '.join(brands)})")
    return []


def check() -> list[str]:
    """Verify the emitted snapshot still matches its sources. Returns drift descriptions."""
    mpath = os.path.join(OUT, "manifest.json")
    if not os.path.exists(mpath):
        return ["no snapshot emitted yet -- run python3 build/snapshot.py"]
    manifest = json.load(open(mpath, encoding="utf-8"))
    pairs, problems = _plan()
    drift = list(problems)
    live = {dest: src for src, dest in pairs}

    for dest, rec in manifest["files"].items():
        out = os.path.join(OUT, dest)
        if not os.path.exists(out):
            drift.append(f"{dest}: missing from the snapshot")
            continue
        if dest == "README.md":
            continue
        if _sha(out) != rec["sha256"]:
            drift.append(f"{dest}: hand-edited since it was emitted")
        if dest in live and _sha(live[dest]) != rec["sha256"]:
            drift.append(f"{dest}: source {rec['source']} changed -- re-emit")

    for dest in set(live) - set(manifest["files"]):
        drift.append(f"{dest}: exists in the repo but not in the snapshot -- re-emit")
    return drift


def emit_if_complete() -> None:
    """Called by make.py. Emits once every brand has a current build; otherwise says
    which brand is missing rather than shipping half a snapshot."""
    problems = emit(strict=False)
    for p in problems:
        print(f"snapshot     SKIPPED -- {p}")


if __name__ == "__main__":
    if "--check" in sys.argv:
        d = check()
        if d:
            print("SNAPSHOT DRIFT\n  " + "\n  ".join(d))
            raise SystemExit(1)
        print("snapshot     clean -- every file matches its source")
    else:
        emit()
